// The official MCP TypeScript SDK client drives the server as a real client would (stdio subprocess), against
// lab-web at the analyzed commit. With DEVOS_IT_TRANSCRIPT set, the session is written as Markdown for the report.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { GENERATIONS, LAB_WEB, LAB_WEB_COMMIT, LAB_WEB_REMOTE, TRANSCRIPT, cloneAt, skipUnless } from './env.ts';
import { tmp } from '../helpers.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const SESSION: [string, Record<string, unknown>][] = [
  ['generation_info', {}],
  ['search', { query: 'lease document', limit: 5 }],
  ['symbol', { symbol: 'LeasesService.sign' }],
  ['callers', { symbol: 'LeasesService.sign', depth: 2 }],
  ['who_calls', { route: 'GET /v1/leases/{flowId}' }],
  ['http', { route: '/v1/quotes' }],
  ['routes', { prefix: '/quotes' }],
  ['di', { service: 'LeasesService' }],
  ['implementations', { symbol: 'OnInit' }],
  ['refs', { symbol: 'LeasesService', limit: 5 }],
  ['callees', { symbol: 'LeaseDetail.ngOnInit' }],
  ['messages', {}],
  ['trace', { from: 'LeaseDetail.ngOnInit', to: 'LeasesService' }],
  ['context', { project: '.', cursor: '0' }],
];

test('official SDK client: initialize, list tools, call each tool', { skip: skipUnless(GENERATIONS, LAB_WEB), timeout: 60000 }, async () => {
  const workspace = cloneAt(LAB_WEB, LAB_WEB_COMMIT, LAB_WEB_REMOTE);
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: ['--disable-warning=ExperimentalWarning', join(ROOT, 'src/cli.ts'), 'serve'],
    cwd: workspace,
    env: { PATH: process.env.PATH ?? '', HOME: tmp('mcp-sdk-home-'), DEVOS_MCP_GENERATIONS: GENERATIONS, DEVOS_MCP_OCI: 'off' },
    stderr: 'pipe',
  });
  const client = new Client({ name: 'devos-it-client', version: '0.0.0' });
  await client.connect(transport);
  const lines: string[] = [];
  try {
    const info = client.getServerVersion();
    assert.equal(info?.name, 'devos-intelligence-mcp');
    assert.match(client.getInstructions() ?? '', /WARNING/);
    const { tools } = await client.listTools();
    assert.equal(tools.length, 14);
    lines.push(
      '# MCP session transcript: lab-web-angular',
      '',
      `Client: \`@modelcontextprotocol/sdk\` ${'1.32.2'} \`Client\` over \`StdioClientTransport\`; server \`${info?.name} ${info?.version}\` started as a subprocess with the workspace a clone of \`devos-lab-web\` at \`${LAB_WEB_COMMIT.slice(0, 12)}\`. Generated by \`tests/integration/sdk-client.test.ts\`.`,
      '',
      `Tools listed: ${tools.map((t) => `\`${t.name}\``).join(', ')}.`,
      '',
    );
    for (const [name, args] of SESSION) {
      const r = (await client.callTool({ name, arguments: args })) as { content: { type: string; text: string }[]; isError?: boolean };
      assert.equal(r.isError, false, `${name}: ${r.content[0]?.text}`);
      const text = r.content.map((c) => c.text).join('\n');
      assert.match(text, /^generation lab-web-angular .* exact match for HEAD\n/, name);
      lines.push(`## \`${name}\` ${JSON.stringify(args)}`, '', '```text', text.length > 2500 ? text.slice(0, 2500) + '\n[transcript cut at 2500 characters]' : text, '```', '');
    }
  } finally {
    await client.close();
  }
  if (TRANSCRIPT) writeFileSync(TRANSCRIPT, lines.join('\n'));
});
